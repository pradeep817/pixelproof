import type { DesignDoc } from '../../ir.js';
import { snake } from '../../naming.js';

/**
 * Golden test that renders the generated screen at the exact Figma frame size.
 * `flutter test --update-goldens` writes the PNG the verification step compares
 * against the Figma render (next milestone: automatic pixel diff + fidelity score).
 */
export function goldenTest(doc: DesignDoc, screenClass: string, screenFile: string, packageName: string): string {
  const { width, height } = doc.root.box;
  const name = snake(doc.root.name) || 'screen';
  const families = [...new Set(doc.fonts.map(f => f.replace(/ \d+( italic)?$/, '')))];
  return `// GENERATED by pixelproof. Renders ${screenClass} at the Figma frame size (${width}x${height}).
// Run: flutter test --update-goldens test/pixelproof/${name}_golden_test.dart
//
// Fonts: put the design's font files in assets/fonts/ (file names starting with the family,
// e.g. ${families[0] ?? 'Inter'}-Regular.ttf). Without them a system font stands in, so text is
// readable but slightly different from Figma.
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:${packageName}/generated/${screenFile.replace(/\.dart$/, '')}.dart';

const _families = <String>[${families.map(f => `'${f}'`).join(', ')}];
const _fallbacks = <String>[
  '/System/Library/Fonts/Supplemental/Arial.ttf',
  '/Library/Fonts/Arial.ttf',
  '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
  'C:/Windows/Fonts/arial.ttf',
];

Future<void> _loadFonts() async {
  final dir = Directory('assets/fonts');
  for (final family in _families) {
    final prefix = family.replaceAll(' ', '').toLowerCase();
    var files = dir.existsSync()
        ? dir
            .listSync()
            .whereType<File>()
            .where((f) => f.uri.pathSegments.last.replaceAll(' ', '').toLowerCase().startsWith(prefix))
            .toList()
        : <File>[];
    if (files.isEmpty) {
      files = _fallbacks.map(File.new).where((f) => f.existsSync()).take(1).toList();
    }
    if (files.isEmpty) continue;
    final loader = FontLoader(family);
    for (final f in files) {
      loader.addFont(Future.value(ByteData.sublistView(f.readAsBytesSync())));
    }
    await loader.load();
  }
}

void main() {
  setUpAll(_loadFonts);

  testWidgets('${screenClass} renders at design size', (tester) async {
    tester.view.physicalSize = const Size(${width}, ${height});
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.reset);

    await tester.pumpWidget(const MaterialApp(debugShowCheckedModeBanner: false, home: ${screenClass}()));
    // SVG icons and images decode asynchronously: let real I/O finish before the snapshot.
    await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 500)));
    await tester.pumpAndSettle();

    await expectLater(find.byType(${screenClass}), matchesGoldenFile('goldens/${name}.png'));
  });
}
`;
}
