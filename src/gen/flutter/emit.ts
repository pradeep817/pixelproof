import type { DesignDoc, IRNode, Paint, RGBA, Shadow, TextStyle } from '../../ir.js';
import { call, format, list, num, type Expr } from './dart.js';
import { dartIdent, dartString, pascal, snake } from '../../naming.js';

export interface FlutterOptions {
  /** Root frame fills the device width instead of the fixed design width. */
  responsiveWidth: boolean;
  /** Wrap the screen in a vertical scroll view. */
  scroll: boolean;
  /** Import path of the tokens file, relative to the screen file. */
  tokensImport: string;
}

export const defaultOptions: FlutterOptions = { responsiveWidth: true, scroll: true, tokensImport: 'app_tokens.g.dart' };

type Axis = 'fixed' | 'hug' | 'expand' | 'infinite';
interface Place { parent: 'row' | 'column' | 'stack' | 'root'; boundedW: boolean; boundedH: boolean; parentNode?: IRNode }

interface Ctx {
  doc: DesignDoc;
  opts: FlutterOptions;
  usesSvg: boolean;
  usesTokens: boolean;
  usesImageFilter: boolean;
  textParams?: Map<string, string>; // text node id -> param name (inside a component body)
  components: Map<string, ComponentClass>;
  colorTokens: Map<string, RGBA>;
  textTokens: Map<string, TextStyle>;
  warnings: string[];
}

interface ComponentClass {
  className: string;
  params: { name: string; nodeId: string; sample: string }[];
  body: string;            // formatted body expression with param references
  signature: string;
  tappable: boolean;
}

export interface FlutterOutput {
  screenFile: string;
  screenClass: string;
  code: string;
  tokensCode: string;
  pubspecAssets: string[];
  dependencies: string[];
  warnings: string[];
}

export function generateFlutter(doc: DesignDoc, options: Partial<FlutterOptions> = {}): FlutterOutput {
  const opts = { ...defaultOptions, ...options };
  const ctx: Ctx = {
    doc, opts, usesSvg: false, usesTokens: false, usesImageFilter: false, components: new Map(),
    colorTokens: new Map(doc.colors.map(c => [c.name, c.color])),
    textTokens: new Map(doc.textStyles.map(t => [t.name, t.style])),
    warnings: [],
  };
  collectWarnings(doc.root, ctx.warnings);

  const root: IRNode = structuredClone(doc.root);
  if (opts.responsiveWidth) inferAnchors(root);
  const rootPlace: Place = { parent: 'root', boundedW: true, boundedH: true };
  let body = core(root, rootPlace, ctx);
  if (opts.scroll) body = call('SingleChildScrollView', { child: body });

  const screenClass = `${pascal(root.name) || 'Generated'}Screen`.replace(/ScreenScreen$/, 'Screen');
  const bg = root.fills.find(f => f.kind === 'solid');
  const scaffold = call('Scaffold', {
    backgroundColor: bg && bg.kind === 'solid' ? color(bg.color, bg.token, ctx) : undefined,
    body,
  });

  const classes = [
    widgetClass(screenClass, [], format(scaffold, 2), false),
    ...[...ctx.components.values()].map(c => widgetClass(c.className, c.params.map(p => p.name), c.body, c.tappable)),
  ];

  const imports = [
    ...(ctx.usesImageFilter ? [`import 'dart:ui' show ImageFilter;`, ''] : []),
    `import 'package:flutter/material.dart';`,
  ];
  if (ctx.usesSvg) imports.push(`import 'package:flutter_svg/flutter_svg.dart';`);
  if (ctx.usesTokens) imports.push(`import '${opts.tokensImport}';`);

  const header = [
    `// GENERATED by pixelproof from Figma file ${doc.fileKey}, node ${root.id} ("${root.name}").`,
    '// Do not edit by hand: re-run `pixelproof pull` to update. Put custom logic in a separate file.',
    ...(doc.omitted.length ? ['//', `// Left out (drawn by the phone, not the app): ${doc.omitted.join(', ')}. Use --keep-system-ui to include.`] : []),
    ...(ctx.warnings.length ? ['//', '// Not generated yet (check these by eye):', ...ctx.warnings.map(w => `//   - ${w}`)] : []),
  ];

  const code = [...header, '', ...imports, '', classes.join('\n\n'), ''].join('\n');
  return {
    screenFile: `${snake(root.name) || 'generated'}.g.dart`,
    screenClass,
    code,
    tokensCode: tokensFile(doc),
    pubspecAssets: [...new Set(doc.assets.map(a => a.file.slice(0, a.file.lastIndexOf('/') + 1)))].sort(),
    dependencies: ctx.usesSvg ? ['flutter_svg'] : [],
    warnings: ctx.warnings,
  };
}

function widgetClass(name: string, params: string[], body: string, tappable: boolean): string {
  const ctorParams = ['super.key', ...params.map(p => `required this.${p}`), ...(tappable ? ['this.onTap'] : [])];
  const fields = [...params.map(p => `  final String ${p};`), ...(tappable ? ['  final VoidCallback? onTap;'] : [])];
  return [
    `class ${name} extends StatelessWidget {`,
    `  const ${name}({${ctorParams.join(', ')}});`,
    ...(fields.length ? ['', ...fields] : []),
    '',
    '  @override',
    '  Widget build(BuildContext context) {',
    `    return ${body};`,
    '  }',
    '}',
  ].join('\n');
}

// ---------------------------------------------------------------- sizing

function resolve(n: IRNode, p: Place): { w: Axis; h: Axis } {
  if (p.parent === 'root') {
    return { w: n.width === 'hug' ? 'hug' : 'infinite', h: 'fixed' };
  }
  if (p.parent === 'stack' || n.absolute) {
    return { w: n.constraints.h === 'both' ? 'infinite' : 'fixed', h: n.constraints.v === 'both' ? 'infinite' : 'fixed' };
  }
  const pn = p.parentNode!;
  const row = p.parent === 'row';
  const mainS = row ? n.width : n.height;
  const crossS = row ? n.height : n.width;
  const mainBounded = row ? p.boundedW : p.boundedH;
  const crossBounded = row ? p.boundedH : p.boundedW;
  const parentCrossFixedish = row ? pn.height !== 'hug' : pn.width !== 'hug';

  const main: Axis = mainS === 'fill' ? (mainBounded ? 'expand' : 'fixed') : mainS;
  const cross: Axis = crossS === 'fill' ? (crossBounded && parentCrossFixedish ? 'infinite' : 'fixed') : crossS;
  if (n.kind === 'text' && main === 'hug' && cross === 'hug') return { w: 'hug', h: 'hug' };
  return row ? { w: main, h: cross } : { w: cross, h: main };
}

function childPlace(n: IRNode, sz: { w: Axis; h: Axis }, p: Place): Place {
  const mode = n.layout.mode === 'none' || n.kind !== 'frame' && n.kind !== 'ellipse' ? 'stack' : n.layout.mode;
  // A hug axis is bounded only when the parent passes a loose bound down (cross axis of a flex).
  const hugBoundedW = p.parent === 'column' || p.parent === 'root' ? p.boundedW : p.parent === 'stack';
  const hugBoundedH = p.parent === 'row' ? p.boundedH : p.parent === 'stack';
  return {
    parent: mode,
    boundedW: sz.w === 'hug' ? hugBoundedW : true,
    boundedH: sz.h === 'hug' ? hugBoundedH : true,
    parentNode: n,
  };
}

// ---------------------------------------------------------------- nodes

/** Widget for a node without the wrappers its parent adds (Expanded / Positioned). */
function core(n: IRNode, p: Place, ctx: Ctx): Expr {
  if (n.component?.instance && !ctx.textParams) {
    const ref = componentRef(n, p, ctx);
    if (ref) return ref;
  }
  const sz = resolve(n, p);
  let w: Expr;
  if (n.kind === 'text') w = textWidget(n, sz, ctx);
  else if (n.kind === 'vector') w = svgWidget(n, ctx);
  else w = frameWidget(n, sz, p, ctx);
  if (n.layerBlur) {
    ctx.usesImageFilter = true;
    w = call('ImageFiltered', { imageFilter: `ImageFilter.blur(sigmaX: ${num(n.layerBlur)}, sigmaY: ${num(n.layerBlur)})`, child: w });
  }
  if (n.backgroundBlur) {
    // Frosted glass: blur what is behind the layer, clipped to the layer's shape.
    ctx.usesImageFilter = true;
    const filter = call('BackdropFilter', { filter: `ImageFilter.blur(sigmaX: ${num(n.backgroundBlur)}, sigmaY: ${num(n.backgroundBlur)})`, child: w });
    const radius = borderRadius(n);
    w = n.kind === 'ellipse' ? call('ClipOval', { child: filter }) : radius ? call('ClipRRect', { borderRadius: radius, child: filter }) : call('ClipRect', { child: filter });
  }
  if (n.opacity < 1) w = call('Opacity', { opacity: num(n.opacity), child: w });
  return w;
}

/** Node as a child of its parent: adds Expanded in flex, Positioned in stacks. */
function placed(n: IRNode, p: Place, ctx: Ctx): Expr {
  const w = core(n, p, ctx);
  if (p.parent === 'stack' || n.absolute) return positioned(n, p.parentNode!, w);
  const sz = resolve(n, p);
  const main = p.parent === 'row' ? sz.w : sz.h;
  return main === 'expand' ? call('Expanded', { child: w }) : w;
}

function textWidget(n: IRNode, sz: { w: Axis; h: Axis }, ctx: Ctx): Expr {
  const t = n.text!;
  const param = ctx.textParams?.get(n.id);
  const align = t.style.align === 'left' ? undefined : `TextAlign.${t.style.align}`;
  const text = call('Text', { style: textStyle(t.style, ctx), textAlign: align }, [param ?? dartString(t.characters)]);
  const width = sz.w === 'fixed' ? num(n.box.width) : sz.w === 'infinite' ? 'double.infinity' : undefined;
  return width ? call('SizedBox', { width, child: text }) : text;
}

function svgWidget(n: IRNode, ctx: Ctx): Expr {
  const param = ctx.textParams?.get(n.id);
  const path = param ?? dartString(n.asset!.file);
  if (n.asset!.format === 'png') {
    return call('Image.asset', { width: num(n.box.width), height: num(n.box.height), fit: 'BoxFit.contain' }, [path]);
  }
  ctx.usesSvg = true;
  return call('SvgPicture.asset', { width: num(n.box.width), height: num(n.box.height) }, [path]);
}

function frameWidget(n: IRNode, sz: { w: Axis; h: Axis }, p: Place, ctx: Ctx): Expr {
  const cp = childPlace(n, sz, p);
  const flow = n.children.filter(c => !c.absolute);
  const abs = n.children.filter(c => c.absolute);
  let child: Expr | undefined;

  // Absolute children are positioned against the frame's outer box, so when a flex frame
  // has them, padding moves from the Container onto the flow content inside the Stack.
  let padding = n.layout.mode !== 'none' ? edgeInsets(n) : undefined;
  if (n.layout.mode !== 'none' && flow.length) {
    child = flex(n, sz, flow.map(c => placed(c, cp, ctx)), ctx);
    if (abs.length) {
      if (padding) { child = call('Padding', { padding, child }); padding = undefined; }
      const sp: Place = { parent: 'stack', boundedW: true, boundedH: true, parentNode: n };
      child = call('Stack', { clipBehavior: n.clip ? undefined : 'Clip.none', children: list([child, ...abs.map(c => placed(c, sp, ctx))]) });
    }
  } else if (n.children.length) {
    const sp: Place = { parent: 'stack', boundedW: true, boundedH: true, parentNode: n };
    child = call('Stack', { clipBehavior: n.clip ? undefined : 'Clip.none', children: list(n.children.map(c => placed(c, sp, ctx))) });
  }

  const deco = decoration(n, ctx);
  const width = sz.w === 'fixed' ? num(n.box.width) : sz.w === 'infinite' ? 'double.infinity' : undefined;
  const height = sz.h === 'fixed' ? num(n.box.height) : sz.h === 'infinite' ? 'double.infinity' : undefined;

  if (!deco.main && !padding) {
    if (!width && !height) return child ?? call('SizedBox', {}, [], true);
    return call('SizedBox', { width, height, child });
  }
  const clip = n.clip && deco.main ? 'Clip.antiAlias' : undefined;
  // A plain solid colour reads better as Container(color:) than a one-field BoxDecoration.
  const colorOnly = !clip && deco.main && typeof deco.main !== 'string' && deco.main.kind === 'call'
    && deco.main.name === 'BoxDecoration' && deco.main.args.length === 1 && deco.main.args[0].key === 'color';
  let out: Expr = call('Container', {
    width, height, padding, clipBehavior: clip,
    color: colorOnly ? (deco.main as { args: { value: Expr }[] }).args[0].value : undefined,
    decoration: colorOnly ? undefined : deco.main, child,
  });
  for (const under of deco.under) out = call('DecoratedBox', { decoration: under, child: out });
  return out;
}

function flex(n: IRNode, sz: { w: Axis; h: Axis }, children: Expr[], ctx: Ctx): Expr {
  const L = n.layout;
  if (L.wrap) {
    return call('Wrap', { spacing: L.gap ? num(L.gap) : undefined, runSpacing: L.gap ? num(L.gap) : undefined, children: list(children) });
  }
  const row = L.mode === 'row';
  const hugMain = row ? sz.w === 'hug' : sz.h === 'hug';
  const mainMap = { start: undefined, center: 'MainAxisAlignment.center', end: 'MainAxisAlignment.end', spaceBetween: 'MainAxisAlignment.spaceBetween' };
  const crossMap = { start: 'CrossAxisAlignment.start', center: undefined, end: 'CrossAxisAlignment.end', stretch: 'CrossAxisAlignment.stretch', baseline: 'CrossAxisAlignment.baseline' };
  void ctx;
  return call(row ? 'Row' : 'Column', {
    mainAxisSize: hugMain ? 'MainAxisSize.min' : undefined,
    mainAxisAlignment: mainMap[L.mainAlign],
    crossAxisAlignment: crossMap[L.crossAlign],
    textBaseline: L.crossAlign === 'baseline' ? 'TextBaseline.alphabetic' : undefined,
    spacing: L.gap ? num(L.gap) : undefined,
    children: list(children),
  });
}

function positioned(n: IRNode, parent: IRNode, child: Expr): Expr {
  const px = parent.box.x, py = parent.box.y;
  const left = n.box.x - px, top = n.box.y - py;
  const right = px + parent.box.width - (n.box.x + n.box.width);
  const bottom = py + parent.box.height - (n.box.y + n.box.height);
  const a: Record<string, Expr | undefined> = {};
  let centred = false;
  switch (n.constraints.h) {
    case 'end': a.right = num(right); a.width = num(n.box.width); break;
    case 'both': a.left = num(left); a.right = num(right); break;
    case 'center': a.left = '0'; a.right = '0'; centred = true; break;
    default: a.left = num(left); a.width = num(n.box.width);
  }
  switch (n.constraints.v) {
    case 'end': a.bottom = num(bottom); a.height = num(n.box.height); break;
    case 'both': a.top = num(top); a.bottom = num(bottom); break;
    default: a.top = num(top); a.height = num(n.box.height);
  }
  if (centred) child = call('Align', { alignment: 'Alignment.topCenter', child });
  return call('Positioned', { ...a, child });
}

/**
 * Designers rarely set constraints on a free-form screen, so Figma's default "Left" would pin
 * everything to the left on wider phones. When the screen fills the device width, infer the
 * intent from the layout: full width or equal side margins stretch, centred layers stay centred,
 * layers hugging the right edge stay right.
 */
function inferAnchors(root: IRNode) {
  const pw = root.box.width;
  for (const c of root.children) {
    if (!c.absolute && root.layout.mode !== 'none') continue;
    if (c.constraints.h !== 'start') continue;
    const left = c.box.x - root.box.x;
    const right = pw - left - c.box.width;
    if (Math.abs(left) <= 1 && Math.abs(right) <= 1) c.constraints.h = 'both';
    else if (Math.abs(left - right) <= 1.5 && c.box.width >= pw * 0.5) c.constraints.h = 'both';
    else if (Math.abs(left - right) <= 1.5) c.constraints.h = 'center';
    else if (right < left && right <= pw * 0.25) c.constraints.h = 'end';
  }
}

// ---------------------------------------------------------------- styling

function decoration(n: IRNode, ctx: Ctx): { main?: Expr; under: Expr[] } {
  const fills = [...n.fills];
  const top = fills.pop();
  const under = fills.reverse().map(f => call('BoxDecoration', { ...paintArgs(f, ctx), borderRadius: borderRadius(n) }, [], false));
  const hasAny = top || n.stroke || n.shadows.length || n.radius.some(r => r > 0) && n.clip;
  if (!hasAny) return { under };
  const paint = top ? paintArgs(top, ctx) : {};
  const shadows = n.shadows.length ? list(n.shadows.map(s => shadow(s, ctx))) : undefined;
  if (n.kind === 'ellipse') {
    return {
      main: call('ShapeDecoration', { ...paint, shape: call('OvalBorder', { side: n.stroke ? borderSide(n, ctx) : undefined }), shadows }),
      under,
    };
  }
  return {
    main: call('BoxDecoration', {
      ...paint,
      border: n.stroke ? call('Border.fromBorderSide', {}, [borderSide(n, ctx)]) : undefined,
      borderRadius: borderRadius(n),
      boxShadow: shadows,
    }),
    under,
  };
}

function paintArgs(f: Paint, ctx: Ctx): Record<string, Expr> {
  switch (f.kind) {
    case 'solid': return { color: color(f.color, f.token, ctx) };
    case 'linear': return {
      gradient: call('LinearGradient', {
        begin: alignment(f.from), end: alignment(f.to),
        colors: list(f.stops.map(s => color(s.color, undefined, ctx))),
        stops: list(f.stops.map(s => num(s.position))),
      }),
    };
    case 'radial': return {
      gradient: call('RadialGradient', {
        center: alignment(f.center), radius: num(f.radius),
        colors: list(f.stops.map(s => color(s.color, undefined, ctx))),
        stops: list(f.stops.map(s => num(s.position))),
      }),
    };
    case 'image': {
      const fit = { cover: 'BoxFit.cover', contain: 'BoxFit.contain', fill: 'BoxFit.fill', tile: undefined }[f.fit];
      return { image: call('DecorationImage', { image: call('AssetImage', {}, [dartString(f.ref)]), fit, repeat: f.fit === 'tile' ? 'ImageRepeat.repeat' : undefined }) };
    }
  }
}

const alignment = ([x, y]: [number, number]) => `Alignment(${num(x * 2 - 1)}, ${num(y * 2 - 1)})`;

function borderSide(n: IRNode, ctx: Ctx): Expr {
  const s = n.stroke!;
  const align = { inside: undefined, center: 'BorderSide.strokeAlignCenter', outside: 'BorderSide.strokeAlignOutside' }[s.align];
  return call('BorderSide', { color: color(s.color, s.token, ctx), width: num(s.width), strokeAlign: align });
}

function borderRadius(n: IRNode): Expr | undefined {
  const [tl, tr, br, bl] = n.radius;
  if (n.kind === 'ellipse' || (!tl && !tr && !br && !bl)) return undefined;
  if (tl === tr && tr === br && br === bl) return `const BorderRadius.all(Radius.circular(${num(tl)}))`;
  const r = (v: number) => (v ? `Radius.circular(${num(v)})` : undefined);
  return call('BorderRadius.only', { topLeft: r(tl), topRight: r(tr), bottomRight: r(br), bottomLeft: r(bl) }, [], true);
}

/**
 * Figma strokes never push content inward, but Flutter's Container adds the border width
 * to the padding. Subtract it so children sit exactly where Figma puts them.
 */
function edgeInsets(n: IRNode): Expr | undefined {
  const s = n.stroke;
  const inset = !s ? 0 : s.align === 'inside' ? s.width : s.align === 'center' ? s.width / 2 : 0;
  const p = n.layout.padding;
  const [t, r, b, l] = [p.top, p.right, p.bottom, p.left].map(v => Math.max(0, v - inset));
  if (!t && !r && !b && !l) return undefined;
  if (t === r && r === b && b === l) return `const EdgeInsets.all(${num(t)})`;
  if (t === b && l === r) return `const EdgeInsets.symmetric(horizontal: ${num(l)}, vertical: ${num(t)})`;
  return `const EdgeInsets.fromLTRB(${num(l)}, ${num(t)}, ${num(r)}, ${num(b)})`;
}

/** Figma's blur radius is CSS-like (sigma = blur / 2); Flutter's blurRadius maps to sigma = 0.57735 * r + 0.5. */
export const flutterBlur = (figmaBlur: number) => Math.max(0, (figmaBlur / 2 - 0.5) / 0.57735);

function shadow(s: Shadow, ctx: Ctx): Expr {
  return call('BoxShadow', {
    color: color(s.color, undefined, ctx),
    offset: `Offset(${num(s.x)}, ${num(s.y)})`,
    blurRadius: num(flutterBlur(s.blur)),
    spreadRadius: s.spread ? num(s.spread) : undefined,
  });
}

function textStyle(s: TextStyle, ctx: Ctx): Expr {
  const own = textStyleCall(s, ctx);
  if (s.token && ctx.textTokens.has(s.token)) {
    ctx.usesTokens = true;
    const base = ctx.textTokens.get(s.token)!;
    const same = (k: keyof TextStyle) => JSON.stringify(base[k]) === JSON.stringify(s[k]);
    const layoutSame = (['fontFamily', 'fontSize', 'fontWeight', 'italic', 'lineHeightPx', 'letterSpacingPx', 'decoration'] as const).every(same);
    if (layoutSame) {
      if (same('color')) return `AppTextStyles.${s.token}`;
      return call(`AppTextStyles.${s.token}.copyWith`, { color: color(s.color, s.colorToken, ctx) });
    }
  }
  return own;
}

function textStyleCall(s: TextStyle, ctx: Ctx): Expr {
  const w = Math.min(900, Math.max(100, Math.round(s.fontWeight / 100) * 100));
  return call('TextStyle', {
    fontFamily: dartString(s.fontFamily),
    fontSize: num(s.fontSize),
    fontWeight: w === 400 ? undefined : `FontWeight.w${w}`,
    fontStyle: s.italic ? 'FontStyle.italic' : undefined,
    height: s.lineHeightPx ? `${Math.round((s.lineHeightPx / s.fontSize) * 10000) / 10000}` : undefined,
    leadingDistribution: s.lineHeightPx ? 'TextLeadingDistribution.even' : undefined,
    letterSpacing: s.letterSpacingPx ? num(s.letterSpacingPx) : undefined,
    color: color(s.color, s.colorToken, ctx),
    decoration: s.decoration === 'none' ? undefined : `TextDecoration.${s.decoration}`,
  });
}

function color(c: RGBA, token: string | undefined, ctx: Ctx): string {
  if (token && ctx.colorTokens.has(token)) { ctx.usesTokens = true; return `AppColors.${token}`; }
  return colorLiteral(c);
}

export function colorLiteral(c: RGBA): string {
  const h = (v: number) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0').toUpperCase();
  return `const Color(0x${h(c.a)}${h(c.r)}${h(c.g)}${h(c.b)})`;
}

// ---------------------------------------------------------------- components

/**
 * Every Figma component becomes one reusable widget class. Text layers become String
 * parameters; instances whose body differs (overridden colours, sizes) are inlined instead.
 */
function componentRef(n: IRNode, p: Place, ctx: Ctx): Expr | null {
  // Text layers and icons (instance-swapped vectors) become String parameters.
  const texts: IRNode[] = [];
  const icons: IRNode[] = [];
  const walk = (x: IRNode) => {
    if (x.kind === 'text') texts.push(x);
    else if (x.kind === 'vector' && x !== n) icons.push(x);
    x.children.forEach(walk);
  };
  walk(n);
  const used = new Set<string>();
  const unique = (base: string) => { let name = base; for (let k = 2; used.has(name); k++) name = `${base}${k}`; used.add(name); return name; };
  const params = [
    ...texts.map((t, i) => ({
      name: unique(dartIdent(t.name === t.text?.characters ? (texts.length === 1 ? 'label' : `text${i + 1}`) : t.name, 'label')),
      nodeId: t.id, sample: t.text!.characters,
    })),
    ...icons.map(v => ({ name: unique('icon'), nodeId: v.id, sample: v.asset!.file })),
  ];

  const tappable = /button|btn|cta|chip|tab/i.test(n.component!.name);
  const saved = ctx.textParams;
  ctx.textParams = new Map(params.map(pr => [pr.nodeId, pr.name]));
  const bodyExpr = core({ ...n, component: undefined }, p, ctx);
  ctx.textParams = saved;
  const wrapped = tappable ? call('GestureDetector', { onTap: 'onTap', child: bodyExpr }) : bodyExpr;
  const body = format(wrapped, 2);
  const signature = `${params.map(pr => pr.name).join(',')}|${body}`;

  const key = n.component!.key;
  let cls = ctx.components.get(key);
  if (!cls) {
    let className = pascal(n.component!.name.replace(/=/g, ' ')) || 'Component';
    if ([...ctx.components.values()].some(c => c.className === className)) className = `${className}${ctx.components.size + 1}`;
    cls = { className, params, body, signature, tappable };
    ctx.components.set(key, cls);
  } else if (cls.signature !== signature) {
    return null; // overridden instance: inline it
  }
  return call(cls.className, Object.fromEntries(params.map(pr => [pr.name, dartString(pr.sample)])));
}

function collectWarnings(n: IRNode, out: string[]) {
  for (const w of n.warnings) out.push(`${n.name}: ${w}`);
  n.children.forEach(c => collectWarnings(c, out));
}

// ---------------------------------------------------------------- tokens

export function tokensFile(doc: DesignDoc): string {
  const lines = [
    '// GENERATED by pixelproof from your Figma colour and text styles. Do not edit by hand.',
    '',
    // Only import Flutter when there is something to define, or the analyzer flags it as unused.
    ...(doc.colors.length || doc.textStyles.length
      ? [`import 'package:flutter/material.dart';`, '']
      : ['// No colour or text styles in this design yet: apply styles in Figma to fill these in.', '']),
    'abstract final class AppColors {',
    ...doc.colors.map(c => `  static const ${c.name} = ${colorLiteral(c.color).replace('const ', '')};`),
    '}',
    '',
    'abstract final class AppTextStyles {',
    ...doc.textStyles.map(t => {
      const s = t.style;
      const w = Math.min(900, Math.max(100, Math.round(s.fontWeight / 100) * 100));
      const parts = [
        `fontFamily: ${dartString(s.fontFamily)}`,
        `fontSize: ${num(s.fontSize)}`,
        w !== 400 ? `fontWeight: FontWeight.w${w}` : '',
        s.italic ? 'fontStyle: FontStyle.italic' : '',
        s.lineHeightPx ? `height: ${Math.round((s.lineHeightPx / s.fontSize) * 10000) / 10000}` : '',
        s.lineHeightPx ? 'leadingDistribution: TextLeadingDistribution.even' : '',
        s.letterSpacingPx ? `letterSpacing: ${num(s.letterSpacingPx)}` : '',
        `color: ${colorLiteral(s.color).replace('const ', '')}`,
      ].filter(Boolean);
      return `  static const ${t.name} = TextStyle(\n${parts.map(p => `    ${p},`).join('\n')}\n  );`;
    }),
    '}',
    '',
  ];
  return lines.join('\n');
}
